export function createBundledAcademicDataset(): AcademicCoreDataset {
  const topicsByCode = new Map<string, AcademicTopic[]>();
  for (const t of BUNDLED_TOPICS) {
    const code = t.courseCode.toUpperCase();
    if (!topicsByCode.has(code)) {
      topicsByCode.set(code, []);
    }
    topicsByCode.get(code)!.push(t);
  }

  const profiles: CourseProfile[] = BUNDLED_RAW_PROFILES.map((p) => {
    const attachedTopics = topicsByCode.get(p.courseCode.toUpperCase()) || [];
    return {
      ...p,
      topics: attachedTopics.length > 0 ? attachedTopics : p.topics,
    };
  });

  const profilesByCode = new Map<string, CourseProfile>();
  for (const p of profiles) {
    profilesByCode.set(p.courseCode.toUpperCase(), p);
  }

  const courseResolver = new CourseResolver(profiles, BUNDLED_ALIASES);
  const topicResolver = new TopicResolver(BUNDLED_TOPICS);

  const prerequisiteGraph = new PrerequisiteGraph();
  for (const t of BUNDLED_TOPICS) {
    prerequisiteGraph.addTopic(t);
  }
  for (const edge of BUNDLED_PREREQUISITES) {
    prerequisiteGraph.addPrerequisite(
      edge.topicKey,
      edge.prerequisiteTopicKey,
      edge.status,
      edge.evidenceScope,
      edge.notes,
    );
  }

  return {
    profiles,
    profilesByCode,
    aliases: BUNDLED_ALIASES,
    conflicts: BUNDLED_CONFLICTS,
    prerequisites: BUNDLED_PREREQUISITES,
    topics: BUNDLED_TOPICS,
    courseResolver,
    topicResolver,
    prerequisiteGraph,
  };
}
